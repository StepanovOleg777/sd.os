class OpenAIService:
    def __init__(self) -> None:
        self.client = AsyncOpenAI(
            api_key=settings.OPENAI_API_KEY,
        )

        # Временная память одного диалога.
        # Позже заменим на отдельный conversation_id
        # для каждого пользователя / браузера.
        self.previous_response_id: str | None = None

    async def process(
        self,
        message: str,
    ) -> tuple[str, dict[str, Any] | None]:
        if not settings.OPENAI_API_KEY:
            return (
                "OPENAI_API_KEY не настроен.",
                None,
            )

        request_kwargs = {
            "model": settings.OPENAI_MODEL,
            "instructions": SYSTEM_PROMPT,
            "input": message,
            "tools": TOOLS,
        }

        if self.previous_response_id:
            request_kwargs["previous_response_id"] = (
                self.previous_response_id
            )

        response = await self.client.responses.create(
            **request_kwargs
        )

        action = None

        while True:
            function_calls = [
                item
                for item in response.output
                if item.type == "function_call"
            ]

            if not function_calls:
                self.previous_response_id = response.id

                answer = response.output_text.strip()

                if not answer:
                    answer = (
                        "Не удалось сформировать ответ."
                    )

                return (
                    answer,
                    action,
                )

            tool_outputs = []

            for call in function_calls:
                try:
                    arguments = json.loads(
                        call.arguments
                    )
                except json.JSONDecodeError:
                    arguments = {}

                result, new_action = (
                    await self._execute_tool(
                        call.name,
                        arguments,
                    )
                )

                if new_action is not None:
                    action = new_action

                tool_outputs.append(
                    {
                        "type": "function_call_output",
                        "call_id": call.call_id,
                        "output": json.dumps(
                            result,
                            ensure_ascii=False,
                        ),
                    }
                )

            response = await self.client.responses.create(
                model=settings.OPENAI_MODEL,
                instructions=SYSTEM_PROMPT,
                previous_response_id=response.id,
                input=tool_outputs,
                tools=TOOLS,
            )

    async def _execute_tool(
        self,
        name: str,
        arguments: dict,
    ) -> tuple[Any, dict[str, Any] | None]:

        if name == "search_directory":
            try:
                contacts = (
                    await sim_card_tracker_client.search_contacts(
                        query=arguments.get(
                            "query",
                            "",
                        ),
                        department=arguments.get(
                            "department",
                            "",
                        ),
                        position=arguments.get(
                            "position",
                            "",
                        ),
                        location=arguments.get(
                            "location",
                            "",
                        ),
                        supervisor=arguments.get(
                            "supervisor",
                            "",
                        ),
                        status=arguments.get(
                            "status",
                            "",
                        ),
                    )
                )

                return (
                    {
                        "count": len(contacts),
                        "results": contacts,
                    },
                    None,
                )

            except SimCardTrackerError as exc:
                return (
                    {
                        "error": str(exc),
                    },
                    None,
                )

        if name == "prepare_call":
            result = await contact_agent.prepare_call(
                arguments.get(
                    "query",
                    "",
                )
            )

            return (
                {
                    "status": result.status,
                    "answer": result.answer,
                },
                result.action,
            )

        if name == "prepare_email":
            result = await contact_agent.prepare_email(
                arguments.get(
                    "query",
                    "",
                )
            )

            return (
                {
                    "status": result.status,
                    "answer": result.answer,
                },
                result.action,
            )

        if name == "search_products":
            min_price = arguments.get(
                "min_price"
            )
            max_price = arguments.get(
                "max_price"
            )

            # Некоторые модели могут передавать 0
            # для необязательного ценового фильтра.
            # Для каталога это должно означать
            # отсутствие соответствующего ограничения.
            if (
                isinstance(min_price, (int, float))
                and min_price <= 0
            ):
                min_price = None

            if (
                isinstance(max_price, (int, float))
                and max_price <= 0
            ):
                max_price = None

            available_only = arguments.get(
                "available_only",
                True,
            )

            if not isinstance(
                available_only,
                bool,
            ):
                available_only = True

            limit = arguments.get(
                "limit",
                10,
            )

            if not isinstance(limit, int):
                limit = 10

            limit = max(
                1,
                min(
                    limit,
                    10,
                ),
            )

            result = await consult_agent.search_products(
                query=arguments.get(
                    "query",
                    "",
                ),
                min_price=min_price,
                max_price=max_price,
                available_only=available_only,
                limit=limit,
            )

            return (
                result,
                None,
            )

        if name == "get_product":
            product_id = arguments.get(
                "product_id"
            )

            if not isinstance(
                product_id,
                int,
            ):
                return (
                    {
                        "status": "error",
                        "message": (
                            "Не передан корректный ID товара."
                        ),
                    },
                    None,
                )

            result = await consult_agent.get_product(
                product_id
            )

            return (
                result,
                None,
            )

        if name == "compare_products":
            product_ids = arguments.get(
                "product_ids",
                [],
            )

            if not isinstance(
                product_ids,
                list,
            ):
                product_ids = []

            product_ids = [
                product_id
                for product_id in product_ids
                if isinstance(
                    product_id,
                    int,
                )
            ]

            result = (
                await consult_agent.compare_products(
                    product_ids
                )
            )

            return (
                result,
                None,
            )

        return (
            {
                "error": (
                    f"Неизвестный инструмент: {name}"
                ),
            },
            None,
        )


